// Deploys CoffeeRegistry (which deploys the CoffeeBatch implementation it clones)
// and writes the registry address + both ABIs into the frontend.
//
//   npx hardhat node                                       # terminal 1
//   npx hardhat run scripts/deploy.js --network localhost  # terminal 2

const fs = require("fs");
const path = require("path");
const { ethers, network, artifacts } = require("hardhat");

async function main() {
  if (network.name === "hardhat") {
    console.warn(
      "You are deploying to the in-process Hardhat Network, which is destroyed when this script ends. " +
        "Use '--network localhost' with 'npx hardhat node' running."
    );
  }

  const [deployer] = await ethers.getSigners();
  console.log("Deployer:", deployer.address);

  const Registry = await ethers.getContractFactory("CoffeeRegistry");
  const registry = await Registry.deploy();
  await registry.deployed();
  console.log("CoffeeRegistry deployed to:", registry.address);
  console.log("CoffeeBatch implementation:", await registry.batchImplementation());

  // Local development only: register a few step type ids so the flow can be
  // tried right away. Their meaning (e.g. 0 = Harvest, 1 = Sorting...) is
  // defined off-chain by the standards body; on a real network it registers them.
  const LOCAL_STEP_TYPES = 7;
  const { chainId } = await ethers.provider.getNetwork();
  if (chainId === 31337) {
    for (let i = 0; i < LOCAL_STEP_TYPES; i++) {
      await (await registry.addStepType()).wait();
    }
    console.log(`Registered step type ids 0..${LOCAL_STEP_TYPES - 1} (local chain).`);
  }

  saveFrontendFiles(registry.address, chainId);
}

function saveFrontendFiles(registryAddress, chainId) {
  const dir = path.join(__dirname, "..", "frontend", "src", "contracts");
  fs.mkdirSync(dir, { recursive: true });

  const registryAbi = artifacts.readArtifactSync("CoffeeRegistry").abi;
  const batchAbi = artifacts.readArtifactSync("CoffeeBatch").abi;
  // A .ts file with `as const` lets wagmi/viem infer function names and argument types.
  // Batch addresses are not fixed: read them from the registry (batchAt / getBatches / BatchCreated).
  const source =
    "// Generated by scripts/deploy.js. Do not edit by hand.\n" +
    `export const chainId = ${chainId}\n` +
    `export const coffeeRegistryAddress = '${registryAddress}' as const\n` +
    `export const coffeeRegistryAbi = ${JSON.stringify(registryAbi, null, 2)} as const\n` +
    `export const coffeeBatchAbi = ${JSON.stringify(batchAbi, null, 2)} as const\n`;

  const file = path.join(dir, "coffee.ts");
  fs.writeFileSync(file, source);
  console.log("Wrote", path.relative(process.cwd(), file));
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error(error);
    process.exit(1);
  });
